"""Keep the offering redirect list honest: every slug the site has ever published stays reachable.

An offering page that was live is linked, bookmarked and indexed. When it leaves the Airtable inventory —
retired, renamed, or pulled — its URL must 301 to /invest/ rather than 404. That list used to be typed by
hand in gate.js, which broke twice in one day: three offerings came back into Airtable at their old slugs and
were still being redirected away, and one offering's slug changed, leaving the old URL with nowhere to go.

So it is derived instead. build/published-slugs.txt is an append-only ledger of every slug ever built; this
script adds any new ones, then writes the difference against the current inventory to a module the edge gate
imports. A slug that returns to the inventory drops out of the redirect set on its own.

Run by build/build.py after fetch_opportunities.py, so the ledger sees the current inventory.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get('SITE_ROOT') or os.path.dirname(HERE)
LEDGER = os.path.join(HERE, 'published-slugs.txt')
OUT = os.path.join(ROOT, 'netlify', 'edge-functions', 'lib', 'retired-offerings.js')
HEADER = ("# Every offering slug this site has ever published, one per line. Append-only: build/build_redirects.py\n"
          "# adds new slugs on each build and never removes one, because a URL that has been public stays public.\n"
          "# Anything here that is not in the current Airtable inventory is 301'd to /invest/ by the edge gate.\n"
          "# Delete a line only if you want that URL to start returning 404.\n")


def main():
    current = sorted({o['slug'] for o in json.load(open(os.path.join(HERE, 'offerings.json'), encoding='utf-8'))
                      if o.get('slug')})
    if not current:
        print('WARNING: no offerings have slugs, so the redirect list was left as committed.')
        return 0

    known = []
    if os.path.exists(LEDGER):
        known = [ln.strip() for ln in open(LEDGER, encoding='utf-8') if ln.strip() and not ln.startswith('#')]
    added = sorted(set(current) - set(known))
    if added:
        open(LEDGER, 'w', encoding='utf-8').write(HEADER + '\n'.join(sorted(set(known) | set(current))) + '\n')

    retired = sorted(set(known) | set(added) | set(current))
    retired = [s for s in retired if s not in set(current)]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    body = ('// Generated by build/build_redirects.py — do not edit. Offering slugs that were published once and\n'
            '// are no longer in the Airtable inventory; the edge gate 301s each of them to /invest/.\n'
            '// The source of truth is build/published-slugs.txt, which is append-only.\n'
            'export const RETIRED_OFFERINGS = new Set([\n'
            + ''.join("  '%s',\n" % s for s in retired) + ']);\n')
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if body != old:
        open(OUT, 'w', encoding='utf-8').write(body)
    print('[redirects] %d live offerings, %d retired URLs 301 to /invest/%s'
          % (len(current), len(retired), (' (+%d newly published: %s)' % (len(added), ', '.join(added))) if added else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main())
